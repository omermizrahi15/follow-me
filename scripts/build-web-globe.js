#!/usr/bin/env node
/**
 * Generates the follower website's copy of the travel globe (issue #200).
 *
 * The globe is written once, in TypeScript, for the app: the rendering code in
 * src/ui/map/globeClient.ts and the route geometry in
 * src/domain/services/travelRoute.ts. docs/ is a static GitHub Pages site with
 * no build step, so the files it serves are generated from those sources and
 * checked in:
 *
 *   docs/globe/globe.css        the globe stage's styles
 *   docs/globe/globe.js         window.createRouteGlobe + loadMapLibre (pinned, SRI)
 *   docs/globe/travelRoute.js   buildTravelRoute, as an ES module
 *
 * Run `node scripts/build-web-globe.js` after editing either source.
 * `--check` exits non-zero when the checked-in copy is stale (a jest test runs
 * the same comparison, so a forgotten regeneration fails CI).
 */
const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const ROOT = path.join(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'docs', 'globe');
const banner = source =>
  `/* GENERATED by scripts/build-web-globe.js from ${source} — do not edit; edit the source and re-run. */\n`;

function transpile(file, module) {
  const source = fs.readFileSync(path.join(ROOT, file), 'utf8');
  return ts.transpileModule(source, {
    compilerOptions: { module, target: ts.ScriptTarget.ES2019 },
  }).outputText;
}

/** Evaluates globeClient.ts (constants only, no imports) to read its exports. */
function loadGlobeClient() {
  const exports = {};
  new Function('exports', transpile('src/ui/map/globeClient.ts', ts.ModuleKind.CommonJS))(exports);
  return exports;
}

function generate() {
  const client = loadGlobeClient();
  const loader = `
/**
 * Loads the pinned MapLibre GL JS build (same version and integrity hashes as
 * the app) on demand, so a feed with nothing to plot never downloads it.
 */
window.loadMapLibre = function () {
  if (window.maplibregl) return Promise.resolve(window.maplibregl);
  if (window.__maplibrePromise) return window.__maplibrePromise;
  window.__maplibrePromise = new Promise(function (resolve, reject) {
    var css = document.createElement('link');
    css.rel = 'stylesheet';
    css.href = ${JSON.stringify(client.MAPLIBRE_CSS)};
    css.integrity = ${JSON.stringify(client.MAPLIBRE_CSS_SRI)};
    css.crossOrigin = 'anonymous';
    document.head.appendChild(css);
    var script = document.createElement('script');
    script.src = ${JSON.stringify(client.MAPLIBRE_JS)};
    script.integrity = ${JSON.stringify(client.MAPLIBRE_JS_SRI)};
    script.crossOrigin = 'anonymous';
    script.onload = function () { resolve(window.maplibregl); };
    script.onerror = function () { window.__maplibrePromise = null; reject(new Error('MapLibre failed to load')); };
    document.head.appendChild(script);
  });
  return window.__maplibrePromise;
};
`;
  return {
    'globe.css': `${banner('src/ui/map/globeClient.ts')}${client.GLOBE_CSS.trimStart()}`,
    'globe.js': `${banner('src/ui/map/globeClient.ts')}${client.GLOBE_CLIENT_JS.trimStart()}${loader}`,
    'travelRoute.js': `${banner('src/domain/services/travelRoute.ts')}${transpile(
      'src/domain/services/travelRoute.ts',
      ts.ModuleKind.ES2020,
    )}`,
  };
}

module.exports = { generate, OUT_DIR };

if (require.main === module) {
  const files = generate();
  if (process.argv.includes('--check')) {
    const stale = Object.keys(files).filter(name => {
      const file = path.join(OUT_DIR, name);
      return !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== files[name];
    });
    if (stale.length > 0) {
      console.error(`Stale: ${stale.join(', ')} — run: node scripts/build-web-globe.js`);
      process.exit(1);
    }
  } else {
    fs.mkdirSync(OUT_DIR, { recursive: true });
    for (const [name, content] of Object.entries(files)) fs.writeFileSync(path.join(OUT_DIR, name), content);
    console.log(`Wrote ${Object.keys(files).map(n => `docs/globe/${n}`).join(', ')}`);
  }
}
